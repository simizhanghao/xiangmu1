"""Unified trace schema for the Evidence-Cost-Aware Deep Research Agent.

Defines the intermediate representation (TraceRecord) that all agent rollouts
(Search-R1 style, FlashRAG, ReAct, direct answer) will be converted into, so
that metrics, rewards, and trace viewers consume one single format.

This module only defines the schema and structural validation. It contains no
parsing, file I/O, model, or training logic. Standard library only.

Schema version: 0.1
"""

from dataclasses import asdict as _dataclass_asdict
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

SCHEMA_VERSION = "0.1"

# The six legal step types of a trace.
#   think       : explicit reasoning text generated by the model
#   internal    : explicit routing output where the model chooses to rely on
#                 parametric knowledge instead of external retrieval
#   search      : a search query issued by the model
#   observation : retriever output injected into the context (environment)
#   evidence    : supporting snippet actively selected/emitted by the model
#   answer      : the final answer
STEP_TYPES = frozenset(
    {
        "think",
        "internal",
        "search",
        "observation",
        "evidence",
        "answer",
    }
)

# Step-level loss mask semantics:
#   True  -> tokens of this step are model-generated targets and will enter
#            SFT loss / policy loss / KL in the future.
#   False -> content injected by the environment; must NOT be a training
#            target (structured abstraction of Search-R1's info_mask).
# Note: "evidence" originates from observations, but it is actively selected
# and emitted by the model, so it is NOT masked.
EXPECTED_LOSS_MASK: Dict[str, bool] = {
    "think": True,
    "internal": True,
    "search": True,
    "observation": False,
    "evidence": True,
    "answer": True,
}


@dataclass
class Document:
    """A retrieved document/passage as returned by a retriever."""

    document_id: str
    title: str = ""
    text: str = ""
    source: str = ""
    url: Optional[str] = None
    rank: Optional[int] = None
    score: Optional[float] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class Evidence:
    """A supporting snippet the model selected from a retrieved Document."""

    evidence_id: str
    document_id: str
    text: str
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class TraceStep:
    """One step of a trace. Meaning of `content` depends on `step_type`."""

    step_id: int
    step_type: str
    content: str
    loss_mask: bool = True
    document_ids: List[str] = field(default_factory=list)
    evidence_ids: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class RewardBreakdown:
    """Raw per-component reward scores (unweighted; no computation here)."""

    answer_reward: float = 0.0
    evidence_reward: float = 0.0
    citation_reward: float = 0.0
    format_reward: float = 0.0
    cost_reward: float = 0.0
    duplicate_query_penalty: float = 0.0


@dataclass
class CostInfo:
    """Post-run aggregate cost statistics (steps remain the raw facts)."""

    search_count: int = 0
    unique_query_count: int = 0
    duplicate_query_count: int = 0
    retrieved_document_count: int = 0
    prompt_tokens: int = 0
    generated_tokens: int = 0
    observation_tokens: int = 0
    latency_ms: float = 0.0


@dataclass
class TraceRecord:
    """One complete trajectory for one question.

    `sample_id` identifies the original question (maps from Search-R1's
    `extra_info.index`; shared by all rollouts of the same question and used
    later for GRPO grouping). `trace_id` identifies this specific rollout.
    """

    question: str
    gold_answers: List[str] = field(default_factory=list)
    trace_id: str = ""
    sample_id: str = ""
    steps: List[TraceStep] = field(default_factory=list)
    documents: List[Document] = field(default_factory=list)
    evidences: List[Evidence] = field(default_factory=list)
    reward_breakdown: RewardBreakdown = field(default_factory=RewardBreakdown)
    cost_info: CostInfo = field(default_factory=CostInfo)
    metadata: Dict[str, Any] = field(default_factory=dict)
    schema_version: str = SCHEMA_VERSION

    @property
    def final_answer(self) -> str:
        """Content of the last `answer` step; "" if there is none.

        Read-only and not serialized: the answer step is the single source
        of truth, no second copy of the final answer is stored.
        """
        for step in reversed(self.steps):
            if step.step_type == "answer":
                return step.content
        return ""

    def asdict(self) -> Dict[str, Any]:
        """Return the record as a plain nested dict (recursive)."""
        return _dataclass_asdict(self)

    def to_jsonl_dict(self) -> Dict[str, Any]:
        """Return the dict form to be dumped as one JSONL line."""
        return self.asdict()


def validate_trace_record(record: TraceRecord) -> List[str]:
    """Structurally validate a TraceRecord.

    Returns an empty list if the record is valid, otherwise a list of
    human-readable error strings (all errors, not just the first).

    Only structural legality is checked here. Answer correctness, evidence
    quality, citation faithfulness, search quality, and reward sanity belong
    to metrics / reward / failure analysis, not to this validator.
    """
    errors: List[str] = []

    if not isinstance(record, TraceRecord):
        return [f"record must be a TraceRecord, got {type(record).__name__}"]

    if not record.question or not record.question.strip():
        errors.append("question must be non-empty")

    # --- steps ---
    answer_indices: List[int] = []
    for position, step in enumerate(record.steps):
        prefix = f"steps[{position}]"

        if step.step_id != position:
            errors.append(
                f"{prefix}: step_id must increase consecutively from 0, "
                f"expected {position}, got {step.step_id}"
            )

        if step.step_type not in STEP_TYPES:
            errors.append(
                f"{prefix}: invalid step_type '{step.step_type}', "
                f"must be one of {sorted(STEP_TYPES)}"
            )
        else:
            expected_mask = EXPECTED_LOSS_MASK[step.step_type]
            if step.loss_mask != expected_mask:
                errors.append(
                    f"{prefix}: step_type '{step.step_type}' requires "
                    f"loss_mask={expected_mask}, got {step.loss_mask}"
                )
            if step.step_type == "answer":
                answer_indices.append(position)

        if not step.content or not step.content.strip():
            errors.append(f"{prefix}: content must be non-empty")

    if len(answer_indices) != 1:
        errors.append(
            f"record must contain exactly one answer step, "
            f"found {len(answer_indices)}"
        )
    elif answer_indices[0] != len(record.steps) - 1:
        errors.append("the answer step must be the last step")

    # --- documents / evidences ---
    document_ids: List[str] = [doc.document_id for doc in record.documents]
    if len(document_ids) != len(set(document_ids)):
        errors.append("Document.document_id values must be unique")

    evidence_ids: List[str] = [ev.evidence_id for ev in record.evidences]
    if len(evidence_ids) != len(set(evidence_ids)):
        errors.append("Evidence.evidence_id values must be unique")

    known_document_ids = set(document_ids)
    known_evidence_ids = set(evidence_ids)

    for ev in record.evidences:
        if ev.document_id not in known_document_ids:
            errors.append(
                f"evidence '{ev.evidence_id}' references unknown "
                f"document_id '{ev.document_id}'"
            )

    for position, step in enumerate(record.steps):
        prefix = f"steps[{position}]"
        for doc_id in step.document_ids:
            if doc_id not in known_document_ids:
                errors.append(
                    f"{prefix}: references unknown document_id '{doc_id}'"
                )
        for ev_id in step.evidence_ids:
            if ev_id not in known_evidence_ids:
                errors.append(
                    f"{prefix}: references unknown evidence_id '{ev_id}'"
                )

    # --- cost info ---
    cost = record.cost_info
    for field_name in (
        "search_count",
        "unique_query_count",
        "duplicate_query_count",
        "retrieved_document_count",
        "prompt_tokens",
        "generated_tokens",
        "observation_tokens",
        "latency_ms",
    ):
        value = getattr(cost, field_name)
        if value < 0:
            errors.append(f"cost_info.{field_name} must be >= 0, got {value}")

    return errors
